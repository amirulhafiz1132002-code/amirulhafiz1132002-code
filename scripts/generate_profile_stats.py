#!/usr/bin/env python3
"""Generate self-contained GitHub profile statistics SVGs from the public GitHub API."""
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from html import escape
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen
import json
import os
import sys

USERNAME = "amirulhafiz1132002-code"
API = "https://api.github.com"
OUT = Path("profile")
TOKEN = os.environ.get("GITHUB_TOKEN", "")
COLORS = ["#67e8f9", "#2dd4bf", "#818cf8", "#fbbf24", "#fb7185", "#a3e635"]


def api_get(url):
    headers = {
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": "AMRHZ-Profile-Stats",
    }
    if TOKEN:
        headers["Authorization"] = f"Bearer {TOKEN}"
    request = Request(url, headers=headers)
    try:
        with urlopen(request, timeout=25) as response:
            return json.loads(response.read().decode("utf-8"))
    except (HTTPError, URLError, TimeoutError) as exc:
        raise RuntimeError(f"GitHub API request failed for {url}: {exc}") from exc


def fetch_repositories():
    repos = []
    page = 1
    while True:
        batch = api_get(
            f"{API}/users/{USERNAME}/repos?type=owner&sort=updated&per_page=100&page={page}"
        )
        if not isinstance(batch, list):
            raise RuntimeError("Unexpected repository response from GitHub API")
        repos.extend(batch)
        if len(batch) < 100:
            return repos
        page += 1


def fetch_language_totals(repositories):
    totals = {}
    def load(repo):
        return api_get(repo["languages_url"])

    with ThreadPoolExecutor(max_workers=6) as pool:
        for language_map in pool.map(load, repositories):
            if not isinstance(language_map, dict):
                continue
            for language, byte_count in language_map.items():
                totals[language] = totals.get(language, 0) + int(byte_count)
    return totals


def number(value):
    return f"{int(value):,}"


def snapshot_timestamp():
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def format_percentage(value):
    if value <= 0:
        return "0.0%"
    if value < 0.1:
        return "<0.1%"
    if value < 1:
        return f"{value:.2f}%"
    return f"{value:.1f}%"


def stats_svg(profile, repos, snapshot):
    stars = sum(int(repo.get("stargazers_count", 0)) for repo in repos)
    forks = sum(int(repo.get("forks_count", 0)) for repo in repos)
    metrics = [
        ("PUBLIC REPOSITORIES", number(len(repos))),
        ("STARS ON OWNED REPOS", number(stars)),
        ("FORKS ON OWNED REPOS", number(forks)),
        ("FOLLOWERS", number(profile.get("followers", 0))),
    ]
    cells = []
    x_positions = [28, 392, 28, 392]
    y_positions = [82, 82, 160, 160]
    for index, ((label, value), x, y) in enumerate(zip(metrics, x_positions, y_positions)):
        color = COLORS[index]
        cells.append(
            f'<rect x="{x}" y="{y}" width="340" height="62" rx="12" fill="#102638" stroke="#24465b"/>'
            f'<rect x="{x}" y="{y}" width="4" height="62" rx="2" fill="{color}"/>'
            f'<text x="{x + 18}" y="{y + 23}" fill="#9fb5c5" font-size="11" '
            f'font-family="Arial, sans-serif" letter-spacing="1">{escape(label)}</text>'
            f'<text x="{x + 18}" y="{y + 49}" fill="#f1f5f9" font-size="22" '
            f'font-weight="700" font-family="Arial, sans-serif">{escape(value)}</text>'
        )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="760" height="246" viewBox="0 0 760 246" role="img" aria-labelledby="title desc">'
        '<title id="title">GitHub profile statistics</title>'
        '<desc id="desc">Public GitHub repository, star, fork, and follower statistics for AMRHZ.</desc>'
        '<rect width="760" height="246" rx="18" fill="#071522"/>'
        '<text x="28" y="35" fill="#67e8f9" font-size="17" font-weight="700" '
        'font-family="Arial, sans-serif" letter-spacing="1.4">GITHUB PROFILE STATISTICS</text>'
        '<text x="28" y="56" fill="#8da6b8" font-size="11" font-family="Arial, sans-serif">'
        f'PUBLIC DATA SNAPSHOT · GENERATED BY AMRHZ GITHUB ACTIONS · {escape(snapshot)}</text>'
        + "".join(cells)
        + '</svg>'
    )


def languages_svg(language_totals, snapshot):
    total = sum(language_totals.values())
    ranked = sorted(language_totals.items(), key=lambda item: item[1], reverse=True)[:6]
    pieces = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="760" height="270" viewBox="0 0 760 270" role="img" aria-labelledby="title desc">',
        '<title id="title">Most used public repository languages</title>',
        '<desc id="desc">Programming language byte totals across owned, non-fork public repositories.</desc>',
        '<rect width="760" height="270" rx="18" fill="#071522"/>',
        '<text x="28" y="35" fill="#67e8f9" font-size="17" font-weight="700" font-family="Arial, sans-serif" letter-spacing="1.4">MOST USED PUBLIC REPOSITORY LANGUAGES</text>',
        f'<text x="28" y="56" fill="#8da6b8" font-size="11" font-family="Arial, sans-serif">OWNED, NON-FORK REPOSITORIES · BY GITHUB-REPORTED LANGUAGE BYTES · {escape(snapshot)}</text>',
    ]
    if not ranked or total == 0:
        pieces.append('<text x="28" y="125" fill="#cbd5e1" font-size="14" font-family="Arial, sans-serif">No language data is available yet.</text>')
    else:
        y = 83
        for index, (language, byte_count) in enumerate(ranked):
            percent = byte_count * 100 / total
            color = COLORS[index]
            width = max(1.5, 480 * percent / 100)
            pieces.extend([
                f'<text x="28" y="{y + 13}" fill="#e2e8f0" font-size="13" font-family="Arial, sans-serif">{escape(language)}</text>',
                f'<rect x="220" y="{y}" width="480" height="16" rx="8" fill="#183246"/>',
                f'<rect x="220" y="{y}" width="{width:.2f}" height="16" rx="8" fill="{color}"/>',
                f'<text x="720" y="{y + 13}" fill="#cbd5e1" font-size="12" text-anchor="end" font-family="Arial, sans-serif">{escape(format_percentage(percent))}</text>',
            ])
            y += 28
    pieces.append('</svg>')
    return "".join(pieces)


def main():
    if not TOKEN:
        raise RuntimeError("GITHUB_TOKEN is required; pass the workflow GITHUB_TOKEN.")
    profile = api_get(f"{API}/users/{USERNAME}")
    all_repos = fetch_repositories()
    public_repos = [repo for repo in all_repos if not repo.get("private", False)]
    original_repos = [repo for repo in public_repos if not repo.get("fork", False)]
    language_totals = fetch_language_totals(original_repos) if original_repos else {}

    snapshot = snapshot_timestamp()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "stats.svg").write_text(stats_svg(profile, public_repos, snapshot), encoding="utf-8")
    (OUT / "top-langs.svg").write_text(languages_svg(language_totals, snapshot), encoding="utf-8")
    print(
        f"Generated profile cards: {len(public_repos)} owned public repositories; "
        f"{len(original_repos)} non-fork repositories with language data. Snapshot: {snapshot}."
    )


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"ERROR: {error}", file=sys.stderr)
        raise
